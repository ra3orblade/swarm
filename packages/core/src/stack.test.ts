describe("manifestKind", () => {
  test("recognises every manifest and nothing else", () => {
    expect(manifestKind("bun.lock")).toBe("bun.lock");
    expect(manifestKind("apps/web/pnpm-lock.yaml")).toBe("pnpm-lock");
    expect(manifestKind("package-lock.json")).toBe("npm-lock");
    expect(manifestKind("yarn.lock")).toBe("yarn-lock");
    expect(manifestKind("uv.lock")).toBe("uv.lock");
    expect(manifestKind("poetry.lock")).toBe("poetry.lock");
    expect(manifestKind("requirements.txt")).toBe("requirements");
    expect(manifestKind("requirements-dev.txt")).toBe("requirements");
    expect(manifestKind(".github/workflows/ci.yml")).toBe("workflow");
    expect(manifestKind(".github/actions/setup/action.yaml")).toBe("action");
    expect(manifestKind("bun.lockb")).toBeNull();
    expect(manifestKind("package.json")).toBeNull();
    expect(manifestKind("README.md")).toBeNull();
  });
});

describe("parsers", () => {
  test("bun.lock: resolved versions, workspace scope, nested keys, workspace packages skipped", () => {
    const rows = parseBunLock(BUN);
    expect(rows.map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "@biomejs/biome@2.5.9:development",
      "hono@4.6.3:runtime",
      "typescript@5.9.2:development",
      "zod@3.22.0:runtime",
      "zod@3.23.8:runtime",
    ]);
    expect(rows.every((r) => r.ecosystem === "npm" && r.manifest === "bun.lock")).toBe(true);
  });

  test("pnpm-lock v9: importers give scope, peer suffixes are cut, snapshots are ignored", () => {
    const rows = parsePnpmLock(PNPM9);
    expect(rows.map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "@tanstack/react-query@5.102.8:runtime",
      "clsx@2.1.1:runtime",
      "react@19.2.8:runtime",
      "scheduler@0.26.0:",
      "vite@7.0.4:development",
    ]);
  });

  test("pnpm-lock v5: slash-separated keys and top-level dependencies", () => {
    const rows = parsePnpmLock(PNPM5);
    expect(rows.map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "@babel/code-frame@7.24.2:",
      "lodash@4.17.21:runtime",
    ]);
  });

  test("package-lock v3: nested node_modules, dev flag, links and workspaces skipped", () => {
    const rows = parseNpmLock(NPM3);
    expect(rows.map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "@oxc-project/types@0.152.0:development",
      "postcss@8.5.1:development",
      "three@0.186.1:runtime",
      "vite@8.3.2:development",
    ]);
  });

  test("package-lock v1: the dependencies tree", () => {
    expect(parseNpmLock(NPM1).map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "accepts@1.3.8:runtime",
      "express@4.19.2:runtime",
      "jest@29.7.0:development",
    ]);
  });

  test("yarn.lock v1: several specs per block, scope from package.json", () => {
    const pkg = JSON.stringify({ dependencies: { lodash: "^4" }, devDependencies: {} });
    expect(parseYarnLock(YARN1, pkg).map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "@babel/runtime@7.24.5:",
      "lodash@4.17.21:runtime",
    ]);
  });

  test("yarn.lock berry: npm: specs, the workspace entry and __metadata skipped", () => {
    expect(parseYarnLock(YARN_BERRY).map((r) => `${r.name}@${r.version}`)).toEqual([
      "@scope/thing@2.1.4",
      "left-pad@1.3.0",
    ]);
  });

  test("uv.lock: registry packages, PEP 503 names, scope from the root's declarations", () => {
    const rows = parseUvLock(UV);
    expect(rows.map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "aiohappyeyeballs@2.7.1:",
      "aiohttp@3.14.5:runtime",
      "fast-api@0.120.0:runtime",
      "pytest@8.4.1:development",
      "yarl@1.20.0:",
    ]);
    expect(rows.some((r) => r.name === "backend-v2")).toBe(false);
  });

  test("poetry.lock: category (old) and groups (new)", () => {
    expect(parsePoetryLock(POETRY_OLD).map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "django@4.2.11:runtime",
      "pytest@7.4.4:development",
    ]);
    expect(parsePoetryLock(POETRY_NEW).map((r) => `${r.name}@${r.version}:${r.scope}`)).toEqual([
      "requests@2.32.3:runtime",
      "ruff@0.5.0:development",
    ]);
  });

  test("requirements.txt: pins only, extras and markers stripped, options and ranges skipped", () => {
    expect(parseRequirementsTxt(REQS).map((r) => `${r.name}@${r.version}`)).toEqual([
      "aiohappyeyeballs@2.6.1",
      "aiohttp@3.14.3",
      "cryptography@42.0.5",
      "pyyaml@6.0.1",
    ]);
  });

  test("workflows: owner/repo@ref, local and docker steps skipped, v prefix dropped", () => {
    const rows = parseWorkflowUses(WORKFLOW, ".github/workflows/ci.yml");
    expect(rows.map((r) => `${r.name}@${r.version}`)).toEqual([
      "actions/checkout@4",
      "github/codeql-action@8f1a2b3c4d5e6f708192a3b4c5d6e7f8a9b0c1d2",
      "oven-sh/setup-bun@2.0.1",
    ]);
    expect(rows[0]?.ecosystem).toBe("GitHub Actions");
  });

  test("every parser survives an empty or alien file", () => {
    expect(parsePnpmLock("")).toEqual([]);
    expect(parseYarnLock("")).toEqual([]);
    expect(parseUvLock("")).toEqual([]);
    expect(parsePoetryLock("not toml at all")).toEqual([]);
    expect(parseRequirementsTxt("")).toEqual([]);
    expect(parseWorkflowUses("name: x\n", "w.yml")).toEqual([]);
    expect(() => parseBunLock("{ not json")).toThrow();
  });

  test("normalizePyPI follows PEP 503", () => {
    expect(normalizePyPI("Fast_API")).toBe("fast-api");
    expect(normalizePyPI("zope.interface")).toBe("zope-interface");
    expect(normalizePyPI("a__b--c..d")).toBe("a-b-c-d");
  });
});

describe("detectStack", () => {
  test("reads every recognised file, hands yarn its sibling package.json, ignores the rest", () => {
    const rows = detectStack({
      "bun.lock": BUN,
      "apps/py/requirements.txt": REQS,
      "apps/web/yarn.lock": YARN1,
      "apps/web/package.json": JSON.stringify({ devDependencies: { lodash: "^4" } }),
      ".github/workflows/ci.yml": WORKFLOW,
      "README.md": "# nope",
    });
    const by = (e: string) => rows.filter((r) => r.ecosystem === e).length;
    expect(by("npm")).toBe(7);
    expect(by("PyPI")).toBe(4);
    expect(by("GitHub Actions")).toBe(3);
    expect(rows.find((r) => r.name === "lodash")?.scope).toBe("development");
    expect(rows.find((r) => r.name === "lodash")?.manifest).toBe("apps/web/yarn.lock");
  });

  test("an empty folder is an empty stack", () => {
    expect(detectStack({})).toEqual([]);
    expect(stackSummary([])).toEqual({
      total: 0,
      byEcosystem: { npm: 0, PyPI: 0, "GitHub Actions": 0 },
      byScope: { runtime: 0, development: 0, "": 0 },
      manifests: [],
    });
  });

  test("stackSummary counts by ecosystem, scope and manifest", () => {
    const s = stackSummary(detectStack({ "bun.lock": BUN, "requirements.txt": REQS }));
    expect(s.total).toBe(9);
    expect(s.byEcosystem).toEqual({ npm: 5, PyPI: 4, "GitHub Actions": 0 });
    expect(s.byScope).toEqual({ runtime: 3, development: 2, "": 4 });
    expect(s.manifests).toEqual(["bun.lock", "requirements.txt"]);
  });
});
