// ---- release notes: split CHANGELOG.md → window.RELEASE_NOTES (version → { date, md }) so the
// dashboard's "What's New" can show the notes for the running version, offline, no repo needed.
//
// It ships the markdown, not HTML. The panel renders it with the dashboard's own renderer
// (`components/Markdown.tsx`), which is the same one the session log uses — one renderer, one set
// of rules, and no generated markup for the dashboard to inject. The HTML this used to emit wrapped
// every *source* line in its own `<p>`, so a wrapped sentence in the changelog arrived as three
// paragraphs with blank space between them.
{
  const changelogPath = join(here, "../../../CHANGELOG.md");
  const md = readFileSync(changelogPath, "utf8");
  const notes: Record<string, { date: string | null; md: string }> = {};
  let version: string | null = null;
  let body: string[] = [];
  const flush = () => {
    if (version && notes[version]) notes[version].md = body.join("\n").trim();
    body = [];
  };
  for (const line of md.split(/\r?\n/)) {
    const heading = /^##\s+\[([0-9]+\.[0-9]+\.[0-9]+)\](?:\s+[—-]\s+(.+))?/.exec(line);
    if (heading) {
      flush();
      version = heading[1] as string;
      notes[version] = { date: heading[2]?.trim() ?? null, md: "" };
      continue;
    }
    // "Unreleased" is not a release, and the trailing `[0.13.0]: https://…` link definitions are
    // reference syntax this renderer does not read — either one ends the entry being collected.
    if (/^##\s+\[Unreleased\]/.test(line) || /^\[[0-9]/.test(line)) {
      flush();
      version = null;
      continue;
    }
    if (!version) continue;
    // A section inside one version's notes is that entry's top level: `### Added` under a `##`
    // version becomes `## Added`, which the renderer gives the heading the panel styles.
    body.push(line.replace(/^###\s+/, "## "));
  }
  flush();
  writeFileSync(
    join(pub, "release-notes.js"),
    `// generated by tools/build.ts from CHANGELOG.md\nwindow.RELEASE_NOTES = ${JSON.stringify(notes)};\n`,
  );
}

